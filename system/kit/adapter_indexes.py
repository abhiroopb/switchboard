"""Rebuild adapters/PORTABILITY.md, adapters/portability.json and adapters/SKILLS.md from the tree a build ships.

The build calls regenerate(tree) when the tier sets `adapter_indexes: true`, after the overlay and before the
gates, so the indexes list exactly the files that ship. A file keeps the class an earlier index gave it unless a
path rule names its class; a new file is classed by its path and content. Reasons are generic text written here,
never copied from the source's own index.
"""
from __future__ import annotations

import json
import re

Tree = dict[str, bytes]
CLASSES = ("portable", "adapter", "amp-only", "cmux-only")
MEANING = {
    "portable": "Runs or reads the same in any harness: plain Python and shell, Markdown, templates, configs.",
    "adapter": "Policy or docs that mention Amp or cmux; the harness adapter (CLAUDE.md import, Codex AGENTS.md, "
               "Cursor rule, SYSTEM.md) supplies the equivalent and nothing else is needed.",
    "amp-only": "Depends on the Amp plugin API, amp-mem or the amp CLI. Optional outside Amp; the Claude Code hook "
                "in `.claude/hooks/` covers the shell-expressible guardrails.",
    "cmux-only": "Drives cmux or wmux workspaces and tabs. Optional everywhere else; dispatch degrades to running "
                 "tasks in your own terminal.",
}
PATH_RULES = (  # (prefix, class, reason)
    ("system/vendor/", "portable", "pinned third-party skills, copied into the agent's skill folder at install"),
    ("system/amp-plugins/", "amp-only", "Amp plugin bundle"),
    ("system/amp-mem/", "amp-only", "amp-mem memory store"),
    ("system/claude-marketplace/", "adapter", "Claude Code plugin: hooks, slash commands and reviewer agents"),
    (".claude/", "portable", "Claude Code adapter"),
    (".codex/", "portable", "Codex adapter"),
    (".cursor/", "portable", "Cursor adapter"),
    ("system/windows/", "portable", "Windows install and scheduled tasks"),
    ("system/launchd/", "portable", "macOS launchd agents for the loop"),
    ("system/connectors/", "portable", "connector shim: Gmail, Calendar, Drive, Slack and Dropbox over direct APIs"),
    ("system/cmux-sidebars/", "cmux-only", "cmux sidebar"),
)
SKIP = {"adapters/PORTABILITY.md", "adapters/portability.json", "adapters/SKILLS.md"}
AMP_RX = re.compile(r"(?m)^[^#\n]*(?:\bamp (?:threads|-x|--execute|skill)\b|@ampcode/plugin|\bamp-mem\b)")
CMUX_RX = re.compile(r"(?m)^[^#\n]*\b(?:cmux|wmux) (?:workspace|new-workspace|send|read-screen|list-workspaces|select)")
PROSE_RX = re.compile(r"\b(?:Amp|cmux|wmux)\b")
FRONT_RX = re.compile(r"\A---\s*\n(.*?)\n---", re.S)


def classify(rel: str, data: bytes) -> tuple[str, str]:
    for prefix, cls, reason in PATH_RULES:
        if rel.startswith(prefix):
            return cls, reason
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return "portable", "binary asset"
    if rel.endswith((".py", ".sh", ".ts", ".ps1", ".js")):
        if AMP_RX.search(text):
            return "amp-only", "uses the Amp plugin API, amp-mem or the amp CLI"
        if CMUX_RX.search(text):
            return "cmux-only", "drives cmux or wmux workspaces"
        return "portable", "no harness dependency found"
    if rel.endswith(".md") and PROSE_RX.search(text):
        return "adapter", "mentions Amp or cmux in prose; the harness adapter supplies the equivalent"
    return "portable", "no harness dependency found"


def folder(rel: str) -> str:
    parts = rel.split("/")
    if len(parts) == 1:
        return "root"
    return "/".join(parts[:2] if len(parts) > 2 else parts[:1]) + "/"


def portability(tree: Tree, previous: dict) -> tuple[str, str]:
    files: dict[str, dict] = {}
    for rel in sorted(tree):
        if rel in SKIP or rel.startswith(".pm-os-kit/"):
            continue
        cls, reason = classify(rel, tree[rel])
        old = (previous.get(rel) or {}).get("class")
        if old in CLASSES and not any(rel.startswith(p) for p, _, _ in PATH_RULES):
            cls = old
        files[rel] = {"class": cls, "reason": reason}
    counts = {c: sum(1 for v in files.values() if v["class"] == c) for c in sorted(CLASSES)}
    data = json.dumps({"counts": counts, "files": files}, indent=1, ensure_ascii=False) + "\n"
    lines = ["# Portability audit",
             "<!-- Generated by system/kit/adapter_indexes.py at build time from the files that ship. Do not edit. -->",
             "", f"{len(files)} files. Counts: " + ", ".join(f"{counts[c]} {c}" for c in CLASSES) + ".", "",
             "| Class | Meaning |", "|---|---|"] + [f"| `{c}` | {MEANING[c]} |" for c in CLASSES]
    for cls in CLASSES:
        group: dict[str, list[str]] = {}
        for rel, meta in files.items():
            if meta["class"] == cls:
                group.setdefault(folder(rel), []).append(rel)
        lines += ["", f"## {cls} ({counts[cls]})", ""]
        for name in sorted(group):
            rels = group[name]
            reasons = "; ".join(sorted({files[r]["reason"] for r in rels}))
            label = name if name == "root" else f"`{name}`"
            lines.append(f"- {label} ({len(rels)}): {reasons}")
            if len(rels) <= 12:
                lines += [f"  - `{r}`" for r in rels]
    return "\n".join(lines) + "\n", data


def frontmatter(data: bytes) -> dict[str, str]:
    m = FRONT_RX.match(data.decode("utf-8", "replace").replace("\r\n", "\n"))
    out: dict[str, str] = {}
    if not m:
        return out
    key = None
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if kv:
            key, val = kv.group(1), kv.group(2).strip()
            out[key] = "" if val in (">", "|", ">-", "|-") else val.strip("\"'")
        elif key and line[:1] in (" ", "\t"):
            out[key] = (out[key] + " " + line.strip()).strip()
    return out


def skills(tree: Tree) -> str:
    rows = []
    for rel in sorted(tree):
        if re.fullmatch(r"(?:\.agents/skills|system/skill-overrides)/[^/]+/SKILL\.md", rel):
            fm = frontmatter(tree[rel])
            name = fm.get("name") or rel.split("/")[-2]
            desc = (fm.get("description") or "").replace("|", "/")
            rows.append(f"| `{name}` | {desc} | `{rel}` |")
    head = ["# Skills index",
            "<!-- Generated by system/kit/adapter_indexes.py at build time from the SKILL.md frontmatter of every "
            "skill that ships. Do not edit. -->", "",
            "Amp, Claude Code and Codex load these skills from disk (`.agents/skills/`, `~/.agents/skills/`, or",
            "`~/.claude/skills/`; see `adapters/README.md`). Chat tools such as ChatGPT have no skill loader: pick the",
            "skill whose description matches the task and paste the body of its `SKILL.md` (and any file it",
            "references) into the conversation after `adapters/SYSTEM.md`. The third-party skills under",
            "`system/vendor/skills/` are listed in `THIRD_PARTY_NOTICES.md`.", "", f"{len(rows)} skills.", "",
            "| Skill | Use when | File |", "|---|---|---|"]
    return "\n".join(head + rows) + "\n"


def regenerate(tree: Tree) -> list[str]:
    previous: dict = {}
    try:
        previous = json.loads(tree.get("adapters/portability.json", b"{}").decode("utf-8")).get("files") or {}
    except (ValueError, AttributeError):
        previous = {}
    md, js = portability(tree, previous)
    tree["adapters/PORTABILITY.md"] = md.encode("utf-8")
    tree["adapters/portability.json"] = js.encode("utf-8")
    tree["adapters/SKILLS.md"] = skills(tree).encode("utf-8")
    return sorted(SKIP)
