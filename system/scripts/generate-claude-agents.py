#!/usr/bin/env python3
"""Generate Claude Code subagent files from the reviewer personas in sub-agents/.

Each `sub-agents/<slug>.md` (skipping README.md and `_*` files) becomes
`system/claude-marketplace/plugins/pm-os/agents/<slug>.md` with Claude Code
subagent frontmatter (`name`, `description`, `tools`) followed by the persona
body unchanged. Generated files carry an HTML comment marker right after the
frontmatter; a file in the agents directory without that marker is
hand-maintained (for example the codebase-* and thoughts-* agents copied from
~/.claude/agents) and is never overwritten.

Usage:
  python3 system/scripts/generate-claude-agents.py            # dry run: print what would change
  python3 system/scripts/generate-claude-agents.py --write    # write changed files, remove stale generated ones
  python3 system/scripts/generate-claude-agents.py --check    # exit 1 when disk differs from the generated output

Personas are read-only reviewers. Those that review implementations get
`Bash` so they can run the code they review; document, design, and strategy
reviewers get `Read, Grep, Glob` only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


SOURCE_DIR = Path("sub-agents")
AGENTS_DIR = Path("system/claude-marketplace/plugins/pm-os/agents")

READ_ONLY_TOOLS = "Read, Grep, Glob"
SHELL_TOOLS = "Read, Grep, Glob, Bash"

# Personas that review code, systems, or data and may need to run something
# to confirm a finding (code-reviewer: "reach for the shell to confirm";
# debugger: reproduce; test/performance/refactor/api/security: run the code
# under review; incident-reviewer: read logs and state; data-analyst: rerun a
# query or script to check a number). Every other persona reviews prose,
# designs, or strategy and never needs a shell.
SHELL_PERSONAS = {
    "api-contract-reviewer",
    "code-reviewer",
    "data-analyst",
    "debugger",
    "incident-reviewer",
    "performance-reviewer",
    "refactor-architect",
    "security-privacy-reviewer",
    "test-strategist",
}

# "Use when" clauses for personas whose source states when to use them in a
# form the generic "<perspective> to <goal>" derivation cannot read.
USE_WHEN_OVERRIDES = {
    "code-reviewer": (
        "Use when reviewing a shipped or about-to-ship script, CLI, plugin, automation, "
        "or piece of infrastructure as written; use engineer-reviewer for PRDs and specs."
    ),
    "content-ux-writer": (
        "Use when reviewing in-product microcopy (labels, buttons, empty states, errors); "
        "use the writing skill for longer-form and external content."
    ),
}

MARKER_TEMPLATE = (
    "<!-- Generated by system/scripts/generate-claude-agents.py from sub-agents/{slug}.md. "
    "Edit the source persona and rerun with --write. -->"
)
MARKER_PREFIX = "<!-- Generated by system/scripts/generate-claude-agents.py from sub-agents/"

_INLINE_MARKUP = re.compile(r"\*\*|`|__")
_WHITESPACE = re.compile(r"\s+")


def plain_text(markdown: str) -> str:
    """Collapse a markdown paragraph into one plain line."""
    text = _INLINE_MARKUP.sub("", markdown)
    return _WHITESPACE.sub(" ", text).strip()


def first_paragraph(body: str) -> str:
    """First prose paragraph after the H1 (skips headings and blockquotes)."""
    paragraphs = re.split(r"\n\s*\n", body.strip())
    for paragraph in paragraphs:
        stripped = paragraph.strip()
        if not stripped or stripped.startswith(("#", ">", "-", "*", "```")):
            continue
        return plain_text(stripped)
    return ""


def first_heading(body: str) -> str:
    for line in body.splitlines():
        if line.startswith("# "):
            return plain_text(line[2:])
    return ""


_ADOPT_TO = re.compile(r"^Adopt (an? |the )(.+?) perspective to (.+?)\.?$")
_ADOPT = re.compile(r"^Adopt (the perspective of|a perspective focused on) ")


def build_description(slug: str, body: str) -> str:
    """One line: what perspective the persona reviews from, then when to use it.

    Most personas open with "Adopt a <role> perspective to <goal>." That becomes
    "Reviews from a <role> perspective. Use when you need to <goal>." so the
    clause Claude matches on is the goal, not a repeat of the role. Personas
    whose source states when to use them differently use USE_WHEN_OVERRIDES.
    """
    summary = first_paragraph(body) or first_heading(body) or slug.replace("-", " ")
    use_when = USE_WHEN_OVERRIDES.get(slug, "")
    match = _ADOPT_TO.match(summary)
    if match:
        article, role, goal = match.groups()
        summary = f"Reviews from {article}{role} perspective."
        use_when = use_when or f"Use when you need to {goal}."
    else:
        summary = _ADOPT.sub(lambda m: f"Reviews from {m.group(1)} ", summary)
    if not summary.endswith("."):
        summary += "."
    return f"{summary} {use_when}".strip()


def render_agent(slug: str, body: str) -> str:
    description = build_description(slug, body)
    tools = SHELL_TOOLS if slug in SHELL_PERSONAS else READ_ONLY_TOOLS
    lines = [
        "---",
        f"name: {slug}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
        f"tools: {tools}",
        "---",
        "",
        MARKER_TEMPLATE.format(slug=slug),
        "",
        body.strip(),
        "",
    ]
    return "\n".join(lines)


def persona_sources(repo_root: Path) -> list[Path]:
    source_dir = repo_root / SOURCE_DIR
    return sorted(
        path for path in source_dir.glob("*.md")
        if path.name != "README.md" and not path.name.startswith("_")
    )


def is_generated(path: Path) -> bool:
    try:
        return MARKER_PREFIX in path.read_text()
    except OSError:
        return False


def plan(repo_root: Path) -> tuple[dict[str, str], list[str], list[Path]]:
    """Return (slug -> rendered text), warnings, and stale generated files."""
    agents_dir = repo_root / AGENTS_DIR
    rendered: dict[str, str] = {}
    warnings: list[str] = []
    for source in persona_sources(repo_root):
        slug = source.stem
        target = agents_dir / f"{slug}.md"
        if target.exists() and not is_generated(target):
            warnings.append(f"skip {slug}: hand-maintained file already at {target.relative_to(repo_root)}")
            continue
        rendered[slug] = render_agent(slug, source.read_text())

    stale = sorted(
        path for path in agents_dir.glob("*.md")
        if is_generated(path) and path.stem not in rendered
    ) if agents_dir.exists() else []
    return rendered, warnings, stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Write generated agents to the plugin agents/ directory")
    mode.add_argument("--check", action="store_true", help="Exit 1 if any generated agent differs from disk")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    agents_dir = repo_root / AGENTS_DIR
    rendered, warnings, stale = plan(repo_root)

    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    changed: list[str] = []
    for slug, text in rendered.items():
        target = agents_dir / f"{slug}.md"
        if not target.exists() or target.read_text() != text:
            changed.append(slug)
    stale_names = [path.stem for path in stale]

    if args.write:
        agents_dir.mkdir(parents=True, exist_ok=True)
        for slug in changed:
            (agents_dir / f"{slug}.md").write_text(rendered[slug])
            print(f"wrote {slug}")
        for path in stale:
            path.unlink()
            print(f"removed stale {path.stem}")
        print(f"{len(rendered)} agents generated, {len(changed)} written, {len(stale)} removed")
        return 0

    if args.check:
        for slug in changed:
            print(f"differs: {slug}")
        for name in stale_names:
            print(f"stale: {name}")
        if changed or stale_names:
            print(f"{len(changed)} agents differ, {len(stale_names)} stale; run --write", file=sys.stderr)
            return 1
        print(f"{len(rendered)} agents up to date")
        return 0

    for slug in changed:
        print(f"would write {slug}")
    for name in stale_names:
        print(f"would remove {name}")
    if not changed and not stale_names:
        print(f"{len(rendered)} agents up to date")
    else:
        print(f"{len(changed)} to write, {len(stale_names)} to remove; rerun with --write")
    return 0


if __name__ == "__main__":
    sys.exit(main())
