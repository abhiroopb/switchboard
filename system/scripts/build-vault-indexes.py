#!/usr/bin/env python3
"""Generate navigation INDEX.md files for the switchboard Obsidian vault.

The vault is the repository opened in place. Hand-written README.md files stay
the narrative entry points; this script fills the gaps where a folder has many
files and no index (archived workstreams and projects, knowledge, outputs
buckets, notes, system docs). Every generated file carries a banner and is safe
to rerun. The script never writes README.md and never touches source files.

Usage:
    python3 system/scripts/build-vault-indexes.py            # print plan
    python3 system/scripts/build-vault-indexes.py --write    # write INDEX.md files
    python3 system/scripts/build-vault-indexes.py --check    # exit 1 if any file is stale
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from workstream_metadata import first_sentence, format_status_label, load_yaml, normalize_status, titleize_slug  # noqa: E402

RERUN = "python3 system/scripts/build-vault-indexes.py --write"
DATE_PREFIX = re.compile(r"^(\d{4})-(\d{2})-(\d{2})")
MONTH_PREFIX = re.compile(r"^(\d{4})-(\d{2})")
FRONTMATTER_TITLE = re.compile(r"^title:\s*[\"']?(.+?)[\"']?\s*$", re.MULTILINE)
H1 = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)

# Folders that hold runtime state, logs, caches, or generated payloads. They are
# listed in the system index as excluded rather than enumerated.
SYSTEM_EXCLUDED_DIRS = {"state", "logs", "recall", "__pycache__", ".ruff_cache"}

OUTPUT_BUCKET_PURPOSE = {
    "analyses": "Ad-hoc quantitative analyses and their write-ups.",
    "automation-inbox": "Generated digests dropped by automation for later routing.",
    "pages": "Built hosted page bundles (HTML/CSS/JS); no Markdown.",
    "comms-triage": "Comms-triage receipts (`pending/`, `presented/`) and live panels; generated.",
    "daily-rollup": "Daily rollup of outbound writes; generated after Slack/Gmail/Linear/Jira/Airtable writes.",
    "decisions": "Decision drafts awaiting promotion into `knowledge/decisions/`.",
    "gmail-rollup": "Gmail digest snapshots; generated.",
    "leak-report": "Sensitive-content leak scan reports; generated.",

    "meeting-notes": "Meeting notes captured from calendar events (canonical copies).",
    "prds": "PRD drafts before promotion into `knowledge/prds/`.",
    "presentations": "Reveal.js decks (`slides.md`, `theme.css`, exports).",
    "research-synthesis": "Research synthesis drafts.",
    "reviews": "Review notes for the owner (`status: to review` until cleared).",
    "customer-artifact-gallery": "Customer artifact gallery: rendered artifacts plus per-item notes.",
    "slack-messages": "Slack message drafts.",
    "status-updates": "Status update drafts.",
    "summarize-video": "Video summaries.",
    "todo-refresh": "Todo refresh snapshots; generated by the todo routine.",
}
# Big generated buckets get a per-bucket index grouped by month.
PER_BUCKET_INDEX = {"reviews", "meeting-notes", "comms-triage", "daily-rollup", "gmail-rollup", "todo-refresh", "customer-artifact-gallery"}


@dataclass
class Generated:
    path: Path
    content: str


def banner(scope: str) -> list[str]:
    return [
        f"> Generated index of {scope}. Do not edit by hand; rerun `{RERUN}`.",
        "> Hand-written `README.md` files in the same folders remain the narrative entry points.",
        "",
    ]


def note_title(path: Path) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return path.stem
    head = text[:4000]
    if head.startswith("---"):
        end = head.find("\n---", 3)
        if end != -1:
            match = FRONTMATTER_TITLE.search(head[:end])
            if match and match.group(1).strip():
                return match.group(1).strip()
    match = H1.search(head)
    if match and match.group(1).strip():
        return match.group(1).strip()
    return path.stem


def date_of(path: Path) -> str:
    match = DATE_PREFIX.match(path.name)
    return f"{match.group(1)}-{match.group(2)}-{match.group(3)}" if match else ""


def month_of(path: Path) -> str:
    match = MONTH_PREFIX.match(path.name)
    return f"{match.group(1)}-{match.group(2)}" if match else "undated"


def relpath(target: Path, from_dir: Path) -> str:
    return Path(os.path.relpath(target, from_dir)).as_posix()


def md_files(root: Path, exclude_names: set[str] | None = None) -> list[Path]:
    exclude_names = exclude_names or set()
    return sorted(
        p for p in root.rglob("*.md")
        if p.name not in exclude_names and not any(part.startswith(".") for part in p.relative_to(root).parts)
    )


def link(path: Path, from_dir: Path, label: str | None = None) -> str:
    return f"[{label or note_title(path)}]({relpath(path, from_dir)})"


def folder_link(folder: Path, from_dir: Path, label: str | None = None) -> str:
    """Link a folder via a note Obsidian can resolve (folder links count as unresolved).

    Prefers INDEX.md, then README.md, then the first top-level note; falls back to
    plain code text when the folder holds no Markdown at all.
    """
    label = label or folder.name
    for name in ("INDEX.md", "README.md", "CONTEXT.md"):
        if (folder / name).exists():
            return f"[{label}]({relpath(folder / name, from_dir)})"
    notes = sorted(p for p in folder.glob("*.md") if not p.name.startswith("."))
    if notes:
        return f"[{label}]({relpath(notes[0], from_dir)})"
    return f"`{label}/`"


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_None_", ""]
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell.replace("|", "\\|").replace("\n", " ") for cell in row) + " |" for row in rows]
    out.append("")
    return out


def count_tree(root: Path) -> tuple[int, int]:
    md = other = 0
    for p in root.rglob("*"):
        if p.is_file() and not any(part.startswith(".") for part in p.relative_to(root).parts):
            if p.suffix == ".md":
                md += 1
            else:
                other += 1
    return md, other


# --- builders -------------------------------------------------------------


def build_workstream_archive(repo: Path) -> Generated:
    root = repo / "workstreams" / "_archive"
    rows: list[list[str]] = []
    missing_config: list[str] = []
    for d in sorted(p for p in root.iterdir() if p.is_dir()):
        config = load_yaml(d / "config.yaml") if (d / "config.yaml").exists() else {}
        if not config:
            missing_config.append(d.name)
        context = d / "CONTEXT.md"
        name = config.get("name") or titleize_slug(d.name)
        status = format_status_label(normalize_status(config.get("status"))) if config.get("status") else "archived"
        last = str(config.get("last_worked_on") or "").strip() or "—"
        desc = first_sentence(config.get("description")) or "—"
        target = link(context, root, name) if context.exists() else folder_link(d, root, name)
        rows.append([target, status, last, desc])
    lines = ["# Archived workstreams", ""] + banner(f"{len(rows)} archived workstreams under `workstreams/_archive/`")
    lines += [
        "Closed, superseded, or completed workstreams. Each row links to the folder's `CONTEXT.md`. Active workstreams are listed in [workstreams/README.md](../README.md).",
        "",
    ]
    lines += table(["Workstream", "Status at archive", "Last worked", "Description"], rows)
    if missing_config:
        lines += ["## Folders without `config.yaml`", "", "These predate the config convention; open the folder directly.", ""]
        lines += [f"- {folder_link(root / n, root)}" for n in missing_config] + [""]
    return Generated(root / "INDEX.md", "\n".join(lines))


def build_project_archive(repo: Path) -> Generated:
    root = repo / "projects" / "_archive"
    lines = ["# Archived projects", ""] + banner("archived projects under `projects/_archive/`")
    lines += ["Closed or superseded projects. Files are kept in place for provenance; canonical meeting notes live in [outputs/meeting-notes](../../outputs/meeting-notes/INDEX.md).", ""]
    for proj in sorted(p for p in root.iterdir() if p.is_dir()):
        files = md_files(proj, {"INDEX.md"})
        lines += [f"## {titleize_slug(proj.name)} ({len(files)} notes)", ""]
        by_sub: dict[str, list[Path]] = defaultdict(list)
        for f in files:
            sub = f.relative_to(proj).parts[0] if len(f.relative_to(proj).parts) > 1 else "(root)"
            by_sub[sub].append(f)
        for sub in sorted(by_sub, key=lambda s: (s != "(root)", s)):
            lines.append(f"### {proj.name}/{sub}" if sub != "(root)" else f"### {proj.name}/")
            lines.append("")
            lines += [f"- {link(f, root)}" + (f" — {date_of(f)}" if date_of(f) else "") for f in sorted(by_sub[sub], key=lambda p: p.name, reverse=True)]
            lines.append("")
    return Generated(root / "INDEX.md", "\n".join(lines))


def build_knowledge(repo: Path) -> Generated:
    root = repo / "knowledge"
    lines = ["# Knowledge index", ""] + banner("every Markdown note under `knowledge/`")
    lines += ["Narrative guide: [knowledge/README.md](README.md). This index lists every note by folder, including `_archive/`.", ""]
    files = md_files(root, {"INDEX.md", "README.md"})
    by_dir: dict[str, list[Path]] = defaultdict(list)
    for f in files:
        by_dir[f.parent.relative_to(root).as_posix() or "."].append(f)
    for d in sorted(by_dir, key=lambda s: (s.startswith("_archive"), s)):
        readme = root / d / "README.md" if d != "." else None
        heading = "knowledge/" if d == "." else f"knowledge/{d}/"
        lines.append(f"## {heading} ({len(by_dir[d])})")
        if readme and readme.exists():
            lines.append(f"Folder guide: [README]({d}/README.md)")
        lines.append("")
        lines += [f"- {link(f, root)}" for f in sorted(by_dir[d], key=lambda p: p.name)]
        lines.append("")
    return Generated(root / "INDEX.md", "\n".join(lines))


def build_outputs(repo: Path) -> list[Generated]:
    root = repo / "outputs"
    out: list[Generated] = []
    rows: list[list[str]] = []
    for bucket in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith(".")):
        md, other = count_tree(bucket)
        purpose = OUTPUT_BUCKET_PURPOSE.get(bucket.name, "—")
        target = f"[{bucket.name}]({bucket.name}/INDEX.md)" if bucket.name in PER_BUCKET_INDEX else folder_link(bucket, root)
        rows.append([target, str(md), str(other), purpose])
    loose = sorted(p for p in root.glob("*.md") if p.name not in {"README.md", "INDEX.md"})
    lines = ["# Outputs index", ""] + banner("all buckets under `outputs/`")
    lines += ["Narrative guide: [outputs/README.md](README.md). Buckets marked generated are rebuilt by routines; edit the source, not the bucket.", ""]
    lines += table(["Bucket", "Markdown", "Other files", "Purpose"], rows)
    if loose:
        lines += ["## Loose files at `outputs/` root", "", "Early drafts that predate the bucket convention.", ""]
        lines += [f"- {link(f, root)} — {date_of(f)}" for f in loose] + [""]
    out.append(Generated(root / "INDEX.md", "\n".join(lines)))

    for name in sorted(PER_BUCKET_INDEX):
        bucket = root / name
        if not bucket.is_dir():
            continue
        files = md_files(bucket, {"INDEX.md", "README.md"})
        by_month: dict[str, list[Path]] = defaultdict(list)
        for f in files:
            by_month[month_of(f)].append(f)
        lines = [f"# {name} index", ""] + banner(f"{len(files)} Markdown files under `outputs/{name}/`")
        lines += [OUTPUT_BUCKET_PURPOSE.get(name, ""), "", "Back to [outputs index](../INDEX.md).", ""]
        for month in sorted(by_month, reverse=True):
            lines += [f"## {month} ({len(by_month[month])})", ""]
            for f in sorted(by_month[month], key=lambda p: p.as_posix(), reverse=True):
                sub = f.parent.relative_to(bucket).as_posix()
                suffix = f" `{sub}/`" if sub and sub != "." else ""
                lines.append(f"- {link(f, bucket)}{suffix}")
            lines.append("")
        out.append(Generated(bucket / "INDEX.md", "\n".join(lines)))
    return out


def build_notes(repo: Path) -> list[Generated]:
    root = repo / "notes"
    out: list[Generated] = []
    rows = []
    for sub in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith(".")):
        md, other = count_tree(sub)
        purpose = {
            "daily": "One note per day (`YYYY-MM-DD.md`) with the activity log.",
            "chrome-tabs": "Chrome tab snapshots captured by the tabs routine.",
            "knowledge": "Quick knowledge captures awaiting promotion.",
            "sensitive": "Local-only notes; never pushed.",
        }.get(sub.name, "—")
        target = f"[{sub.name}]({sub.name}/INDEX.md)" if sub.name in {"daily", "chrome-tabs"} else folder_link(sub, root)
        rows.append([target, str(md), str(other), purpose])
    lines = ["# Notes index", ""] + banner("folders under `notes/`")
    lines += ["Narrative guide: [notes/README.md](README.md).", ""] + table(["Folder", "Markdown", "Other files", "Purpose"], rows)
    out.append(Generated(root / "INDEX.md", "\n".join(lines)))
    for name in ("daily", "chrome-tabs"):
        sub = root / name
        if not sub.is_dir():
            continue
        files = md_files(sub, {"INDEX.md", "README.md"})
        by_month: dict[str, list[Path]] = defaultdict(list)
        for f in files:
            by_month[month_of(f)].append(f)
        lines = [f"# notes/{name} index", ""] + banner(f"{len(files)} notes under `notes/{name}/`")
        lines += ["Back to [notes index](../INDEX.md).", ""]
        for month in sorted(by_month, reverse=True):
            lines += [f"## {month} ({len(by_month[month])})", ""]
            lines += [f"- {link(f, sub, f.stem)}" for f in sorted(by_month[month], key=lambda p: p.name, reverse=True)]
            lines.append("")
        out.append(Generated(sub / "INDEX.md", "\n".join(lines)))
    return out


def build_system(repo: Path) -> Generated:
    root = repo / "system"
    files = [
        f for f in md_files(root, {"INDEX.md"})
        if not (set(f.relative_to(root).parts[:-1]) & SYSTEM_EXCLUDED_DIRS)
    ]
    by_dir: dict[str, list[Path]] = defaultdict(list)
    for f in files:
        by_dir[f.parent.relative_to(root).as_posix() or "."].append(f)
    lines = ["# System docs index", ""] + banner("human-readable docs under `system/` (scripts, prompts, plugins, config)")
    lines += ["Narrative guide: [system/README.md](README.md).", ""]
    lines += ["## Excluded from this index", ""]
    lines += [f"- `system/{d}/` — runtime state, logs, or caches. Hidden from the Obsidian explorer via `.obsidian/app.json`." for d in sorted(SYSTEM_EXCLUDED_DIRS - {"__pycache__", ".ruff_cache"})]
    lines += ["- Python, shell, YAML, JSON, and plist files are code or config; open them in an editor.", ""]
    for d in sorted(by_dir, key=lambda s: (s != ".", s)):
        heading = "system/" if d == "." else f"system/{d}/"
        lines += [f"## {heading} ({len(by_dir[d])})", ""]
        lines += [f"- {link(f, root)}" for f in sorted(by_dir[d], key=lambda p: p.name)]
        lines.append("")
    return Generated(root / "INDEX.md", "\n".join(lines))


def build_all(repo: Path) -> list[Generated]:
    items = [build_workstream_archive(repo), build_project_archive(repo), build_knowledge(repo)]
    items += build_outputs(repo)
    items += build_notes(repo)
    items.append(build_system(repo))
    return items


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo-root", default=str(Path(__file__).resolve().parents[2]))
    parser.add_argument("--write", action="store_true", help="write INDEX.md files")
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file differs from disk")
    args = parser.parse_args()
    repo = Path(args.repo_root).resolve()

    stale = 0
    for item in build_all(repo):
        text = item.content.rstrip("\n") + "\n"
        current = item.path.read_text(encoding="utf-8") if item.path.exists() else None
        state = "unchanged" if current == text else ("new" if current is None else "stale")
        if state != "unchanged":
            stale += 1
        if args.write and state != "unchanged":
            item.path.write_text(text, encoding="utf-8")
            state = "written"
        print(f"{state:9s} {item.path.relative_to(repo)}  ({text.count(chr(10))} lines)")
    if args.check and stale:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
